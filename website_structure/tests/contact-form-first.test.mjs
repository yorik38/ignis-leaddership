import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(site, path), 'utf8');

test('Contact page embeds the published EU1 HubSpot enquiry form', () => {
  const contact = read('contact.html');
  assert.match(contact, /<body class="contact-page" data-header="light">/);
  assert.match(contact, /<main id="main">\s*<section class="band band-paper contact-section">/);
  assert.match(contact, /<h1>Start the conversation\.<\/h1>/);
  assert.match(contact, /the next gate you need to reach/);
  assert.doesNotMatch(contact, /Where does it hurt|class="page-hero|class="band band-dark home-community"/);
  assert.equal((contact.match(/<h1\b/g) || []).length, 1);
  assert.match(contact, /id="hubspot-contact-form" class="hubspot-contact-form"/);
  assert.match(contact, /src="https:\/\/js-eu1\.hsforms\.net\/forms\/embed\/v2\.js"/);
  assert.match(contact, /hbspt\.forms\.create\(\{region:"eu1",portalId:"149324702",formId:"3c83d1fd-334f-4bf6-9068-47e7f2044ad8",target:"#hubspot-contact-form",onFormSubmitted:function\(\)\{/);
  assert.match(contact, /id="contact-thanks"/);
  assert.match(contact, /Glad you're in\./);
  assert.equal((contact.match(/<h1\b/g) || []).length, 1);
  assert.doesNotMatch(contact, /data-contact-form|action="\/api\/contact"|contact-required-note/);
  assert.match(contact, /Yorik reads every message personally and replies within 2 working days/);
  assert.match(contact, /Prefer to talk now\? Book a 30-minute call/);
  assert.doesNotMatch(contact, /We’ll use your details only to reply to this enquiry|class="contact-privacy"/);
  assert.match(contact, /class="button button-teal" href="https:\/\/calendly\.com\/yorik-tisseau-tmff\/commercial-decision-call" data-calendly-link>Book a call<\/a>/);
  assert.match(contact, /id="hubspot-newsletter-form"/);
  assert.match(contact, /data-community-form/);
  assert.match(contact, /focus\(\{preventScroll:true\}\);thanks\.scrollIntoView\(\{behavior:"smooth",block:"start"\}\)/);
  assert.match(read('assets/whitepaper.js'), /ready\.focus\(\{preventScroll: true\}\);\n    ready\.scrollIntoView\(\{behavior: "smooth", block: "start"\}\)/);
  assert.match(read('assets/capability.js'), /status\.focus\(\{preventScroll:true\}\);status\.scrollIntoView\(\{behavior:"smooth",block:"start"\}\)/);
  assert.match(read('assets/capability.css'), /\.contact-page \.contact-thanks,\.wp-gate-ready,\.signal-signup-success\{scroll-margin-top:112px\}/);
  assert.match(contact, /id="contact-thanks" hidden tabindex="-1"/);
  const signal = contact.slice(contact.indexOf('class="signal-signup-form"'), contact.indexOf('signal-signup-success'));
  assert.match(signal, /placeholder="Work email"/);
  assert.match(signal, /aria-label="Subscribe"/);
  assert.doesNotMatch(signal, />Subscribe</);
  assert.doesNotMatch(signal, /name="company"(?!_)|name="enquiry_topic"|Company \(optional\)|Topic \(optional\)/);
  assert.match(contact, /name="form_started_at"/);
  assert.match(contact, /name="company_website"/);
  assert.match(contact, /data-cookie-settings/);
  assert.equal(existsSync(join(site, 'api/contact.js')), false);
  assert.doesNotMatch(read('vercel.json'), /api\/contact\.js/);
  assert.doesNotMatch(read('assets/script.js'), /fetch\("\/api\/contact"/);
  assert.match(read('scripts/sync-site-chrome.mjs'), /"contact\.html"/);
});
