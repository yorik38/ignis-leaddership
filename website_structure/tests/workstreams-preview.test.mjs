import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const home = readFileSync(join(site, 'index.html'), 'utf8');
const css = readFileSync(join(site, 'assets/workstreams-preview.css'), 'utf8');
const timeGoes = readFileSync(join(site, 'assets/time-goes.css'), 'utf8');
const journey = readFileSync(join(site, 'assets/project-journey.css'), 'utf8');
const js = readFileSync(join(site, 'assets/working-examples.js'), 'utf8');

test('working examples replace the stacked workstream panels', () => {
  const value = home.indexOf('class="band band-paper value-proposition developer-audience"');
  const examples = home.indexOf('id="working-examples-title"');
  const method = home.indexOf('class="band band-paper engagement-offer ignis-method"');
  const adoption = home.indexOf('id="adoption-gap"');
  assert.ok(value >= 0 && examples > value && method > examples && adoption > method);
  assert.match(home, /<h2 id="working-examples-title">Decisions across the project life\.<\/h2>/);
  assert.doesNotMatch(home, /<h2 id="working-examples-title">Working examples<\/h2>/);
  assert.doesNotMatch(home, /class="workstream-panel"|Illustrative workflow/);
  assert.doesNotMatch(home, /FORGE/);
  assert.match(home, /role="tablist"/);
  for (const label of ['Grow your pipeline', 'Steer your portfolio', 'Secure your route to market', 'Tender to financial close']) {
    assert.match(home, new RegExp(`>${label}</button>`));
    assert.match(home, new RegExp(`data-journey-tab="wx-tab-[a-z]+"[^>]*>[\\s\\S]*?<strong>${label}</strong>`));
  }
  assert.match(home, /class="project-journey"/);
  assert.ok(home.indexOf('class="project-journey"') < home.indexOf('Every project starts by rebuilding the last one.'));
  assert.ok(home.indexOf('Every project starts by rebuilding the last one.') < home.indexOf('id="adoption-gap"'));
  const proposition = home.slice(home.indexOf('Every project starts by rebuilding the last one.'), home.indexOf('id="workstreams"'));
  assert.match(proposition, /Most developers still run bids, tenders and route-to-market decisions on spreadsheets, inboxes and memory/);
  assert.match(proposition, /class="time-goes"/);
  assert.match(home, /time-goes\.css\?v=4/);
  assert.match(timeGoes, /\.seg-decisions,\.seg-client\{background:#08756d/);
  assert.doesNotMatch(timeGoes, /#043f3b/);
  assert.match(proposition, /<strong class="teal">agentic workflows built into your team<\/strong>/);
  assert.match(proposition, /Ignis starts with one live commercial workflow/);
  assert.match(proposition, /<strong class="teal">risk needs human control<\/strong>/);
  assert.match(proposition, /<strong class="teal">bounded, repeatable tasks<\/strong>/);
  assert.match(proposition, /<strong class="teal">run together, improve and reuse<\/strong>/);
  assert.match(journey, />li:not\(:last-child\)::after/);
  assert.doesNotMatch(journey, /project-journey-rail::before|bottom:\.2rem/);
  assert.match(home, /project-journey\.css\?v=5/);
  assert.match(timeGoes, /@media\(max-width:600px\)\{[\s\S]*\.developer-audience \.brand-stamp\{display:none\}/);
  assert.match(proposition, /Find and check inputs/);
  assert.match(proposition, /Rebuild analysis/);
  assert.match(proposition, /Prepare first drafts/);
  assert.match(proposition, /Decide and approve/);
  assert.match(proposition, /Agent groundwork, checked by people/);
  assert.match(proposition, /Human judgement and accountability/);
  assert.match(proposition, /What carries forward into the next project/);
  assert.match(proposition, /role="group" aria-labelledby="time-goes-carry-title"/);
  for (const item of ['Approved evidence', 'Decisions', 'Exceptions', 'Lessons', 'Next project']) {
    assert.match(proposition, new RegExp(`>${item}<`));
  }
  assert.match(timeGoes, /\.time-goes-carry-items\{display:grid;grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
  assert.match(timeGoes, /max-width:700px\)\{[\s\S]*\.time-goes-carry-items\{grid-template-columns:1fr/);
  assert.doesNotMatch(proposition, /Illustrative, not measured/);
  assert.match(proposition, /We map where it slows down, which evidence and decisions matter/);
  assert.match(proposition, /your team manages exceptions, exercises judgement and makes commitments/);
  assert.match(proposition, /The result is not an agent added to a broken process/);
  assert.ok(proposition.indexOf('The result is not an agent added to a broken process') < proposition.indexOf('class="developer-sectors"'));
  assert.match(proposition, />Wind</);
  assert.doesNotMatch(proposition, /Each new site starts from scratch|FORGE|Forge/);
  assert.doesNotMatch(home, /wx-accordion|Option A · swipe the chips|Option B · accordion/);
  assert.match(home, /href="\/services">Explore our services /);
  assert.match(css, /max-width:800px\)\{[\s\S]*\.wx-tabs\{[^}]*overflow-x:auto/);
  assert.match(home, /Win the right to develop\./);
  const grow = home.slice(home.indexOf('id="wx-panel-grow"'), home.indexOf('id="wx-panel-steer"'));
  assert.match(grow, /<b>300 MW<\/b>/);
  assert.match(grow, /<b>2035<\/b>/);
  assert.match(grow, /Supply chain and European content/);
  assert.match(grow, /Bid robustness/);
  assert.match(grow, /Financial robustness/);
  assert.doesNotMatch(grow, /900 MW|Grid and connection evidence|Local benefit commitments|Delivery plan/);
  assert.equal((home.match(/ILLUSTRATIVE · <span>example data<\/span>/g) || []).length, 5);
  assert.match(home, /Secure your route to market\./);
  assert.match(home, /Choose the bid you can deliver\./);
  assert.match(home, /Make the Gate 2 call with confidence\./);
  assert.match(home, /Move projects to financial close\./);
  assert.equal((home.match(/class="wx-decision-map"/g) || []).length, 5);
  for (const label of ['Decision', 'Evidence', 'Agent groundwork', 'Human authority', 'Reusable output']) {
    assert.equal((home.match(new RegExp(`<dt>${label}<\\/dt>`, 'g')) || []).length, 5);
  }
  assert.match(home, /Your team decides awards, risk acceptance and final investment commitments/);
  assert.match(home, /Your team owns strategy, pricing and commercial commitments/);
  assert.match(home, /homepage-method\.css\?v=2/);
  assert.match(home, /workstreams-preview\.css\?v=6/);
  assert.match(home, /project-journey\.css\?v=5/);
  assert.match(css, /\.wx-win\+\.wx-win\{width:auto;margin:14px 0 0 12%\}/);
  assert.match(css, /max-width:800px\)\{[\s\S]*\.wx-win\+\.wx-win\{width:100%;margin:14px 0 0\}/);
  assert.match(css, /\.wx-stack thead\{display:none\}/);
  assert.match(js, /data-journey-tab/);
  assert.doesNotMatch(js, /data-wx-accordion/);
  assert.match(js, /ArrowRight/);
  assert.match(js, /aria-selected/);
  assert.match(js, /Home/);
  assert.match(js, /End/);
});
